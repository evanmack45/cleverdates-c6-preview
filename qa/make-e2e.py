# Builds qa/e2e.mjs (the e2e golive-verify runs) from e2e-pages.mjs (pages, share, sitemap, a11y: the original suite) + e2e-scan.mjs (the scan-first home).
# Usage: python3 make-e2e.py   (rerun after editing either source)
import re, sys
c6 = 'c6' in __import__('os').getcwd()
pages = open('e2e-pages.mjs').read()
scan = open('e2e-scan.mjs').read().split('\n')
drop = re.compile(r"^(import |const \[url|const url = process|const \{ dates \}|const get = |let fails|const ok = |const b = |const origin = new URL)")
body = []
for l in scan:
    if l.startswith('// E2E for'): continue
    if l.startswith('const origin = new URL(url).origin, home'): l = "const home = new URL(url).origin + '/';"
    if drop.match(l): continue
    body.append(l)
text = '\n'.join(body)
end = text.index('await b.close();\nconsole.log(fails')
text = text[:end]
pre = "const url = base;\n" if c6 else ""
block = "// ---- scan-first home (from e2e-scan.mjs) ----\n{\n" + pre + "const origin = new URL(url).origin;\n" + text + "\n}\n"
if c6:
    marker = "console.log(fails ? `${fails} FAILED` : 'ALL PASS');"
else:
    marker = "await b.close();\nconsole.log(fails ? `FAILED"
assert pages.count(marker) == 1, marker
out = '// GENERATED by make-e2e.py from e2e-pages.mjs + e2e-scan.mjs. Edit those, then rerun.\n' + pages.replace(marker, block + marker)
open('e2e.mjs', 'w').write(out); print('wrote e2e.mjs')
